// Installed local UI acceptance. Reads archived scientific data; no task writes.
import {chromium} from '@playwright/test';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const out=path.resolve(process.argv[2]);
const expected=JSON.parse(await readFile(path.join(out,'expectations.json'),'utf8'));
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],writes=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('request',r=>{if(r.url().includes('/api/')&&r.method()!=='GET')writes.push(r.method());});
const base='http://127.0.0.1:8768';
try{
 await page.goto(base+'/#/archives/'+expected.trajectory.id);
 await page.getByRole('button',{name:'读取报错与优化轨迹'}).click();
 const panel=page.getByTestId('calculation-analysis');
 await panel.getByLabel('优化步骤').waitFor();
 const options=await panel.getByLabel('计算分段').locator('option').allTextContents();
 const section=options.findIndex(t=>t.startsWith(`第 ${expected.trajectory.segment_index} 段`));
 assert(section>=0);await panel.getByLabel('计算分段').selectOption(String(section));
 await panel.getByLabel('优化步骤').selectOption('1');
 assert((await panel.innerText()).includes(String(expected.trajectory.energies[1])+' Hartree'));
 await panel.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'trajectory-desktop.png'),fullPage:true});
 await panel.getByRole('button',{name:'定位原日志：该步能量来源',exact:true}).click();
 await page.getByTestId('source-excerpt').getByText('已核对 SHA-256',{exact:false}).waitFor();
 assert((await page.getByTestId('source-excerpt').innerText()).includes('SCF Done:'));
 await page.goto(base+'/#/archives/'+expected.error.id);
 await page.getByRole('button',{name:'读取报错与优化轨迹'}).click();
 await page.getByTestId('calculation-analysis').getByText(expected.error.title,{exact:true}).first().waitFor();
 await page.goto(base+'/#/screening');
 await page.getByLabel('项目／候选集合').locator('option').first().waitFor({state:'attached'});
 const groups=await(await page.request.get(base+'/api/project-library')).json();
 const group=groups.items.find(g=>g.archive_ids?.includes(expected.trajectory.id));
 assert(group);await page.getByLabel('项目／候选集合').selectOption(group.id);
 await page.locator('.candidate-layout tbody tr').first().waitFor();
 await page.locator('.candidate-layout .candidate-source').waitFor();
 await page.screenshot({path:path.join(out,'screening-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.screenshot({path:path.join(out,'screening-mobile.png'),fullPage:true});
 await page.goto(base+'/#/task-center');
 await page.getByText('执行端尚未接入：',{exact:false}).waitFor();
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 const queue=await(await page.request.get(base+'/api/task-center')).json();
 assert(queue.enabled);assert(!queue.execution_enabled);assert.equal(queue.items.length,0);
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:path.join(out,'task-center.png'),fullPage:true});
 assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
 await writeFile(path.join(out,'installed-browser-acceptance.json'),JSON.stringify({status:'PASS',checks:['energy-step-selection','source-log-location','diagnostic-marker','screening-real-project','mobile-screening','mobile-task-center','execution-disabled','no-http-writes','no-page-errors'],writes,errors},null,2));
 console.log('PASS: 9 installed real-source checks; no HTTP writes, no remote execution.');
}finally{await browser.close();}
