const files = [indexFile, previous.database, ...capture.files.map(f => f.local_file)];
async function fingerprint() {
  return Promise.all(files.map(async file => { const s = await stat(file, { bigint: true }); return { sha256: createHash('sha256').update(await readFile(file)).digest('hex'), size: String(s.size), inode: String(s.ino), mtime_ns: String(s.mtimeNs), ctime_ns: String(s.ctimeNs) }; }));
}
const before = await fingerprint();
// Token was just generated by this task's preview launcher. Never print/persist it.
