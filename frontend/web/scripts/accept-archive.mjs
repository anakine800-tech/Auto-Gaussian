import { createHash } from 'node:crypto';
import path from 'node:path';
const directory = process.argv[2];
if (!directory || !path.isAbsolute(directory)) throw new Error('Pass absolute private evidence directory');
const root = path.resolve(directory, '../..');
const indexFile = path.join(directory, 'archive-index.json');
const index = JSON.parse(await readFile(indexFile, 'utf8'));
const capture = JSON.parse(await readFile(path.join(directory, 'sample-capture.json'), 'utf8'));
