  await expect(datum('正常 / 错误终止次数')).toHaveText(`${record.summary.normal_count} / ${record.summary.error_count}`);
  await expect(datum('日志终止标记')).toHaveText('正常终止');
  await expect(datum('优化完成标记')).toHaveText('已记录');
  await expect(datum('驻点标记')).toHaveText('已记录');
  await expect(datum(/^频率数量$/)).toHaveText('未记录');
  await expect(datum('虚频数量')).toHaveText('未知（未记录频率）');
  expect(await page.getByTestId('archive-input').textContent()).toBe(record.input.text);
  for (const a of record.artifacts) {
    await expect(page.getByText(a.logical_name, { exact: true })).toBeVisible();
    await expect(page.getByText(`SHA-256 ${a.sha256}`, { exact: true })).toBeVisible();
  }
  await expect(page.getByText('Core Attempt / 实时状态 / 科学验收 / Review：不可用')).toBeVisible();
  await page.screenshot({ path: path.join(directory, 'archive-desktop.png'), fullPage: true });
