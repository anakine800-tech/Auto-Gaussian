expect(record.summary.energy_hartree).toBe(parser.facts.final_energy_hartree);
expect(record.summary.normal_count).toBe(parser.facts.normal_termination_count);
expect(record.summary.error_count).toBe(parser.facts.error_termination_count);
expect(record.summary.optimization).toBe(parser.facts.optimization_completed_marker);
expect(record.summary.stationary_point).toBe(parser.facts.stationary_point_marker);
