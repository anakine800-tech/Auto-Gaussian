def reseal(path, record):
    """Simulate a freshly imported equivalent eigensystem from another BLAS."""
    raw = json.dumps(record, sort_keys=True).encode()
    path.write_bytes(raw)
    (path.parent / 'binding.json').write_bytes(x.catalog.encode(dict(
        schema=x.ANALYSIS, sha256=sha256(raw).hexdigest(), source_sha256=record['source_sha256'])))


def test_reopen_equivalent_eigenvector_signs_and_degenerate_basis(tmp_path):
    root = study_tree(tmp_path)
    source, _, _ = source_package(tmp_path / 'source', eigenvalues=(-.04, .09, .09))
    x.import_hessian(root, source, 'analyses/example')
    path = root / 'analyses/example/analysis.json'
    record = json.loads(path.read_bytes())
    q = np.asarray(record['full_displacements'])
    q[0] *= -1
    # Mix in mass-weighted orthonormal space, then unweight and renormalize.
    weight = np.repeat(np.sqrt(MASS), 3)
    e = q[-2:].reshape(2, 9).T * weight[:, None]
    e /= np.linalg.norm(e, axis=0)
    rot = np.array([[.6, -.8], [.8, .6]])
    d = (e @ rot) / weight[:, None]
    d /= np.linalg.norm(d, axis=0)
    q[-2:] = d.T.reshape(2, 3, 3)
    record['full_displacements'] = q.tolist()
    reseal(path, record)
    assert x.read_analysis(root, path)['status'] == 'available'
    # Even a rewritten seal cannot make arbitrary vectors represent the source Hessian.
    record['full_displacements'][0][0][0] += .05
    reseal(path, record)
    with pytest.raises(ValueError, match='eigensystem'): x.read_analysis(root, path)


@pytest.mark.parametrize('seed', range(6))
def test_printing_precision_boundary_perturbations_and_general_molecules(seed):
    rng = np.random.default_rng(seed)
    xyz = rng.normal(size=(5, 3))
    masses = np.array([12.01073590, 14.00670321, 15.99940492, 1.00794075, 35.45293758])
    spectrum = np.array([-.00002, -.003, .01, .02, .02, .03, .04, .05, .1])
    h, _ = synthetic_matrix(xyz, masses, spectrum)
    # Worst-size changes of coordinates within the g98 printing interval.
    observed = xyz + rng.choice([-1, 1], size=xyz.shape)*.5e-6
    rounded = x.parse_hessian(hessian_bytes(h), 5)
    r = x.convert(rounded, observed, masses, 1)
    assert r['status'] == 'available'
    assert len(r['internal_indices']) == 9
    assert len([v for v in np.array(r['full_eigenvalues'])[np.array(r['internal_indices'])-1] if v < 0]) == 2
    outside = observed.copy(); outside[1] += [.001, -.003, .002]
    assert x.convert(rounded, outside, masses, 1)['status'] == 'external_modes_unresolved'


