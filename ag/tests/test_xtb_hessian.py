def test_degenerate_internal_subspace_and_rotation():
    h, internal = synthetic_matrix(eigenvalues=(-.04, .09, .09))
    q = np.array(x.convert(h, XYZ, MASS, 1)['full_displacements'])
    # Compare the two-dimensional weighted subspace, not individual degenerate vectors.
    weight = np.repeat(np.sqrt(MASS), 3)
    mw = q[-2:].reshape(2, 9).T * weight[:, None]
    u, _, _ = np.linalg.svd(mw, full_matrices=False)
    assert u @ u.T == pytest.approx(internal[:, 1:] @ internal[:, 1:].T, abs=1e-12)
    rot, _ = np.linalg.qr(np.random.default_rng(176).normal(size=(3, 3)))
    transform = np.kron(np.eye(3), rot.T)
    rotated = transform @ h @ transform.T
    r = x.convert((rotated + rotated.T) / 2, XYZ @ rot, MASS, 1)
    assert r['status'] == 'available'
    assert r['full_eigenvalues'] == pytest.approx(x.convert(h, XYZ, MASS, 1)['full_eigenvalues'], abs=1e-14)


@pytest.mark.parametrize('kind', ['truncated', 'extra', 'end', 'nan', 'asymmetric', 'header', 'columns', 'units'])
def test_invalid_format_never_guessed(kind):
    h, _ = synthetic_matrix()
    raw = hessian_bytes(h)
    if kind == 'truncated': raw = b'\n'.join(raw.splitlines()[:-1])
    elif kind == 'extra': raw += b'0.0\n'
    elif kind == 'end': raw += b'$end\n'
    elif kind == 'nan': raw = raw.replace(b'0.0000000000', b'         nan', 1)
    elif kind == 'asymmetric':
        h[1, 2] += .1
        raw = hessian_bytes(h)
    elif kind == 'header': raw = raw.replace(b'$hessian', b'$hessout')
    elif kind == 'columns':
        rows = raw.splitlines(keepends=True)
        rows[1] = rows[1][1:]
        raw = b''.join(rows)
    else: raw = b'# Hartree/angstrom^2\n' + raw
    with pytest.raises(ValueError): x.parse_hessian(raw, 3)


