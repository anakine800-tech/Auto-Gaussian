XYZ = np.array([[0., 0., 0.], [1., 0., 0.], [0., 1., 0.]])
ELEMENTS = ['O', 'H', 'H']
MASS = np.array([x.MASSES[7], x.MASSES[0], x.MASSES[0]])


def synthetic_matrix(xyz=XYZ, masses=MASS, eigenvalues=(-.04, .09, .16)):
    centered = xyz - np.average(xyz, axis=0, weights=masses)
    weight = np.repeat(np.sqrt(masses), 3)
    basis = np.column_stack([np.tile(a, (len(masses), 1)).ravel() * weight for a in np.eye(3)] +
                            [np.cross(a, centered).ravel() * weight for a in np.eye(3)])
    u, _, _ = np.linalg.svd(basis, full_matrices=True)
    internal = u[:, 6:]
    k = (internal * eigenvalues) @ internal.T
    h = k * weight[:, None] * weight[None, :]
    return (h + h.T) / 2, internal


def hessian_bytes(matrix):
    n = len(matrix)
    return ('$hessian'.ljust(80) + '\n' + ''.join(
        ' '*5 + ''.join(f'{v:15.10f}' for v in row[start:start+5]) + '\n'
        for row in matrix for start in range(0, n, 5))).encode()


def geometry_bytes(xyz=XYZ, elements=ELEMENTS):
    rows = [' frequency output generated by the xtb code', ' Standard orientation:',
            ' ' + '-'*68, ' Center Atomic Atomic Coordinates (Angstroms)',
            ' Number Number Type X Y Z', ' ' + '-'*68]
    rows += [f'{i:5d}{x.ATOMIC_NUMBERS[s]:11d}{0:14d}    ' + ''.join(f'{v:12.6f}' for v in row)
             for i, (s, row) in enumerate(zip(elements, xyz), 1)]
    rows += [' ' + '-'*68, ' Harmonic frequencies (synthetic writer emulation, no xTB run)']
    return ('\n'.join(rows) + '\n').encode()


def g98_frequency_bytes(frequencies):
    """Emulate g98fake2's strict pre-print filter and blocks of three."""
    visible = [f for f in frequencies if abs(f) > .1]
    return ''.join(' Frequencies --' + ''.join(f'{f:15.4f}' for f in visible[i:i+3]) + '\n'
                   for i in range(0, max(1, len(visible)), 3)).encode()


def source_package(parent, *, eigenvalues=(-.04, .09, .16), xyz=XYZ, elements=ELEMENTS):
    parent.mkdir()
    masses = np.array([x.MASSES[x.ATOMIC_NUMBERS[s]-1] for s in elements])
    matrix, _ = synthetic_matrix(xyz, masses, eigenvalues)
    command = 'xtb input.xyz --gfn 2 --hess'
    frequencies = [np.sign(v)*x.FREQUENCY_FACTOR*np.sqrt(abs(v)) for v in eigenvalues]
    data = {'hessian': hessian_bytes(matrix), 'geometry': geometry_bytes(xyz, elements) +
            g98_frequency_bytes(frequencies),
            'input': (f'{len(elements)}\nSynthetic input, not a frequency frame\n' +
                      ''.join(s + ' ' + ' '.join(map(str, row)) + '\n' for s, row in zip(elements, xyz))).encode(),
            'stdout': ('* xtb version 6.7.1 (edcfbbe) synthetic text, no run\n'
                       f' program call : {command}\n'
                       'Hessian scale factor :   1.00000\nfrozen atoms in % :   0.00000    0\n'
                       'writing file <hessian>.\n projected vibrational frequencies (cm⁻¹)\n').encode(),
            'stderr': b'normal termination of xtb\n', 'command': command.encode(),
            'build': json.dumps(dict(x.BUILD, channel='https://conda.anaconda.org/conda-forge/osx-64',
                                     note='Synthetic build-record emulation; no execution')).encode()}
    source = dict(schema=x.SCHEMA, files={}, program=dict(version='6.7.1', source_commit=x.COMMIT, build='build'),
                  generation=dict(command='command', controls=[], path='cli-numhess'),
                  hessian=dict(format='xtb-v671-wrhess', unit='hartree/bohr^2', mass_weighted=False, projected=True),
                  geometry=dict(format='xtb-g98', unit='angstrom'),
                  masses=dict(effective_u=masses.tolist(), basis='v671-cli-default-reset'), scale=1.,
                  method='GFN2-xTB', solvent=None, termination='normal', stationarity='unknown')
    for role, raw in data.items():
        (parent / role).write_bytes(raw)
        source['files'][role] = dict(file=role if role != 'input' else 'input.xyz', sha256=sha256(raw).hexdigest())
    (parent / 'input').rename(parent / 'input.xyz')
    path = parent / 'source.json'
    path.write_text(json.dumps(source))
    return path, source, data


def revise(path, source, data=None):
    if data:
        for role, raw in data.items():
            (path.parent / source['files'][role]['file']).write_bytes(raw)
            source['files'][role]['sha256'] = sha256(raw).hexdigest()
    path.write_text(json.dumps(source))


def study_tree(tmp_path):
    root = tmp_path / 'synthetic-study'
